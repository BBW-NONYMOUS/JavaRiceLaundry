    /** Most urgent first. */
    private static final java.util.List<String> URGENCY = java.util.Arrays.asList(
            "Overdue", "Verify payment", "Due today", "Awaiting pickup & payment", "New order", "Awaiting pickup");
    private javax.swing.table.DefaultTableModel model;
    private java.util.List<Order> attention = new java.util.ArrayList<>();

    private void loadDashboard() {
        java.time.LocalDate today = java.time.LocalDate.now();
        titleLabel.setText("Welcome, " + Session.getCurrentUser().getName() + "!");
        dateLabel.setText(today.format(java.time.format.DateTimeFormatter.ofPattern("EEEE, MMMM d, yyyy")));

        int ordersToday = 0, inProcess = 0, paymentsToday = 0, toVerify = 0, ready = 0, readyUnpaid = 0;
        double weightToday = 0, salesToday = 0, verifyAmount = 0;
        attention = new java.util.ArrayList<>();
        for (Order order : Session.getAllOrders()) {
            if (order.getCreatedAt().toLocalDate().equals(today)) {
                ordersToday++;
                weightToday += order.getWeightKg();
            }
            if (order.isPaid() && order.getPaidAt().toLocalDate().equals(today)) {
                paymentsToday++;
                salesToday += order.getTotal();
            }
            if (Order.PENDING_VERIFICATION.equals(order.getPaymentStatus())) {
                toVerify++;
                verifyAmount += order.getTotal();
            }
            if (order.getStatus() < Order.READY) {
                inProcess++;
            } else if (order.getStatus() == Order.READY) {
                ready++;
                readyUnpaid += order.isPaid() ? 0 : 1;
            }
            if (!reason(order, today).isEmpty()) {
                attention.add(order);
            }
        }
        attention.sort(java.util.Comparator.comparingInt((Order o) -> URGENCY.indexOf(reason(o, today)))
                .thenComparing(Order::getExpectedCompletion));

        ordersTodayValue.setText(String.valueOf(ordersToday));
        ordersTodaySub.setText(Ui.kg(weightToday) + " \u2022 " + inProcess + " in process");
        salesTodayValue.setText(Ui.peso(salesToday));
        salesTodaySub.setText(paymentsToday + (paymentsToday == 1 ? " payment received" : " payments received"));
        verifyValue.setText(String.valueOf(toVerify));
        verifySub.setText(Ui.peso(verifyAmount) + " GCash / bank");
        readyValue.setText(String.valueOf(ready));
        readySub.setText(readyUnpaid + " still unpaid");

        loadCharts(today);

        model.setRowCount(0);
        for (Order order : attention) {
            model.addRow(new Object[] {order.getNumber(), order.getCustomerName(), order.getService(),
                Ui.peso(order.getTotal()), order.getPaymentStatus(), order.getStatusName(),
                order.getExpectedCompletion().format(Ui.DATE), reason(order, today)});
        }
        if (attention.isEmpty()) {
            attentionHintLabel.setText("All caught up \u2014 nothing needs attention.");
        } else {
            attentionHintLabel.setText("Double-click an order to update it.");
        }
    }

    private void loadCharts(java.time.LocalDate today) {
        String[] days = new String[7];
        double[] sales = new double[7];
        for (int i = 0; i < 7; i++) {
            days[i] = today.minusDays(6 - i).format(java.time.format.DateTimeFormatter.ofPattern("EEE"));
        }
        int[] counts = new int[Order.CLAIMED];   // Received .. Ready for Pickup
        for (Order order : Session.getAllOrders()) {
            if (order.isPaid()) {
                long ago = java.time.temporal.ChronoUnit.DAYS.between(order.getPaidAt().toLocalDate(), today);
                if (ago >= 0 && ago < 7) {
                    sales[6 - (int) ago] += order.getTotal();
                }
            }
            if (order.getStatus() < Order.CLAIMED) {
                counts[order.getStatus()]++;
            }
        }
        double week = 0;
        for (double day : sales) {
            week += day;
        }
        salesChart.setData(days, sales, true, 6);
        salesChart.setSubtitle(Ui.peso(week) + " this week");

        String[] names = java.util.Arrays.copyOf(Order.STATUSES, Order.CLAIMED);
        double[] values = new double[counts.length];
        for (int i = 0; i < counts.length; i++) {
            values[i] = counts[i];
        }
        statusChart.setData(names, values, false, -1);
        statusChart.setColors(Ui.STATUS_COLORS);
    }

    /** Why an unclaimed order needs staff action, or "" if it doesn't. */
    private String reason(Order order, java.time.LocalDate today) {
        if (order.getStatus() == Order.CLAIMED) {
            return "";
        }
        if (Order.PENDING_VERIFICATION.equals(order.getPaymentStatus())) {
            return "Verify payment";
        }
        if (order.getStatus() < Order.READY && order.getExpectedCompletion().isBefore(today)) {
            return "Overdue";
        }
        if (order.getStatus() < Order.READY && order.getExpectedCompletion().equals(today)) {
            return "Due today";
        }
        if (order.getStatus() == Order.RECEIVED) {
            return "New order";
        }
        if (order.getStatus() == Order.READY) {
            return order.isPaid() ? "Awaiting pickup" : "Awaiting pickup & payment";
        }
        return "";
    }

