    private static final double MAX_WEIGHT = 50;

    private void updateTotal() {
        double weight = Ui.parseNumber(weightField.getText());
        double rate = Session.getDraftService().getRatePerKg();
        totalValueLabel.setText(Ui.peso(weight > 0 && weight <= MAX_WEIGHT ? Order.charge(weight, rate) : 0));
    }

    private void next() {
        double weight = Ui.parseNumber(weightField.getText());
        if (weight <= 0 || weight > MAX_WEIGHT) {
            Ui.warn(this, "Please enter a weight greater than 0 and up to 50 kg.");
            weightField.requestFocusInWindow();
            return;
        }
        Session.setDraftWeight(weight);
        Nav.open(this, new OrderSummaryForm());
    }

