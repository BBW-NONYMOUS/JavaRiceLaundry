    private static final String[] PERIODS = {"Today", "Last 7 Days", "This Month", "All Time"};
    private javax.swing.table.DefaultTableModel serviceModel;

    private boolean inPeriod(Order order) {
        java.time.LocalDate day = order.getCreatedAt().toLocalDate();
        java.time.LocalDate today = java.time.LocalDate.now();
        switch (periodCombo.getSelectedIndex()) {
            case 0:
                return day.equals(today);
            case 1:
                return !day.isBefore(today.minusDays(6));
            case 2:
                return day.getYear() == today.getYear() && day.getMonth() == today.getMonth();
            default:
                return true;
        }
    }

    private void loadReport() {
        if (serviceModel == null) {
            return; // fires while the period list is being filled
        }
        java.util.List<Order> orders = new java.util.ArrayList<>();
        for (Order order : Session.getAllOrders()) {
            if (inPeriod(order)) {
                orders.add(order);
            }
        }
        double weight = 0, collected = 0, outstanding = 0;
        int paid = 0, unpaid = 0, ready = 0, inProcess = 0;
        for (Order order : orders) {
            weight += order.getWeightKg();
            if (order.isPaid()) {
                collected += order.getTotal();
                paid++;
            } else {
                outstanding += order.getTotal();
                unpaid++;
            }
            if (order.getStatus() == Order.READY) {
                ready++;
            } else if (order.getStatus() < Order.READY) {
                inProcess++;
            }
        }
        ordersValue.setText(String.valueOf(orders.size()));
        ordersSub.setText(Ui.kg(weight) + " of laundry");
        salesValue.setText(Ui.peso(collected));
        salesSub.setText(paid + " paid " + (paid == 1 ? "order" : "orders"));
        unpaidValue.setText(Ui.peso(outstanding));
        unpaidSub.setText(unpaid + (unpaid == 1 ? " order" : " orders"));
        readyValue.setText(String.valueOf(ready));
        readySub.setText(inProcess + " still in process");

        serviceModel.setRowCount(0);
        java.util.List<String> serviceNames = new java.util.ArrayList<>();
        java.util.List<Double> serviceSales = new java.util.ArrayList<>();
        for (Service service : Session.getServices()) {
            int count = 0;
            double kg = 0, charges = 0, paidAmount = 0;
            for (Order order : orders) {
                if (order.getService().equals(service.getName())) {
                    count++;
                    kg += order.getWeightKg();
                    charges += order.getTotal();
                    paidAmount += order.isPaid() ? order.getTotal() : 0;
                }
            }
            serviceModel.addRow(new Object[] {service.getName(), count, Ui.kg(kg), Ui.peso(charges), Ui.peso(paidAmount)});
            serviceNames.add(service.getName());
            serviceSales.add(paidAmount);
        }
        double[] sales = new double[serviceSales.size()];
        for (int i = 0; i < sales.length; i++) {
            sales[i] = serviceSales.get(i);
        }
        serviceChart.setData(serviceNames.toArray(new String[0]), sales, true, -1);
        serviceChart.setSubtitle(Ui.peso(collected) + " collected");
        double[] statusCounts = new double[Order.STATUSES.length];
        for (Order order : orders) {
            statusCounts[order.getStatus()]++;
        }
        statusChart.setData(Order.STATUSES, statusCounts, false, -1);
        statusChart.setColors(Ui.STATUS_COLORS);
    }

