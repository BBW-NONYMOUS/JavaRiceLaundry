    private static final String[] CODES = {Service.WASH_AND_FOLD, Service.DRY_CLEANING, Service.IRONING};

    private javax.swing.JRadioButton[] radios() {
        return new javax.swing.JRadioButton[] {washFoldRadio, dryCleaningRadio, ironingRadio};
    }

    private int selectedIndex() {
        javax.swing.JRadioButton[] radios = radios();
        for (int i = 0; i < radios.length; i++) {
            if (radios[i].isSelected()) {
                return i;
            }
        }
        return -1;
    }

    private void refresh() {
        javax.swing.JPanel[] cards = {washFoldCard, dryCleaningCard, ironingCard};
        javax.swing.JRadioButton[] radios = radios();
        for (int i = 0; i < cards.length; i++) {
            Ui.select(cards[i], radios[i].isSelected());
            if (!radios[i].isEnabled()) {
                cards[i].setBackground(new java.awt.Color(0xE8F5E9));
            }
        }
        int index = selectedIndex();
        if (index < 0) {
            selectionLabel.setText("No service is available right now.");
        } else {
            Service service = Session.getService(CODES[index]);
            selectionLabel.setText("Selected: " + service.getName() + "   \u2022   " + Ui.peso(service.getRatePerKg()) + " per kg");
        }
    }

    private void next() {
        int index = selectedIndex();
        if (index < 0) {
            Ui.warn(this, "Please select a laundry service.");
            return;
        }
        Session.setDraftService(CODES[index]);
        Nav.open(this, new WeightForm());
    }

