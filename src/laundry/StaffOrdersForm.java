    private javax.swing.table.DefaultTableModel model;
    private java.util.List<Order> shown = new java.util.ArrayList<>();
    private Order selected;

    private void loadOrders() {
        if (model == null) {
            return; // filters fire while the combo boxes are being filled
        }
        String search = Ui.value(searchField).toLowerCase();
        int status = statusFilter.getSelectedIndex() - 1;
        String payment = paymentFilter.getSelectedIndex() > 0 ? (String) paymentFilter.getSelectedItem() : null;
        Order keep = selected;
        shown = new java.util.ArrayList<>();
        model.setRowCount(0);
        for (Order order : Session.getAllOrders()) {
            boolean matches = search.isEmpty()
                    || order.getNumber().toLowerCase().contains(search)
                    || String.valueOf(order.getId()).equals(search)
                    || order.getCustomerName().toLowerCase().contains(search)
                    || order.getCustomerPhone().contains(search);
            if (matches && (status < 0 || order.getStatus() == status)
                    && (payment == null || payment.equals(order.getPaymentStatus()))) {
                shown.add(order);
                model.addRow(new Object[] {order.getNumber(), order.getCreatedAt().format(Ui.DATE), order.getCustomerName(),
                    order.getService(), Ui.kg(order.getWeightKg()), Ui.peso(order.getTotal()),
                    order.getPaymentMethod(), order.getPaymentStatus(), order.getStatusName()});
            }
        }
        selected = null;
        for (int i = 0; i < shown.size(); i++) {
            if (keep != null && shown.get(i).getId() == keep.getId()) {
                ordersTable.setRowSelectionInterval(i, i);
            }
        }
        showSelected();
    }

    private void showSelected() {
        int row = ordersTable.getSelectedRow();
        selected = row >= 0 && row < shown.size() ? shown.get(row) : null;
        boolean has = selected != null;
        statusCombo.setEnabled(has);
        paymentStatusCombo.setEnabled(has);
        noteField.setEnabled(has);
        saveButton.setEnabled(has);
        viewDocumentButton.setVisible(has);
        if (!has) {
            selectedOrderLabel.setText(shown.isEmpty() ? "No orders match your search." : "Select an order above to update it.");
            selectedInfoLabel.setText("");
            noteField.setText("");
            return;
        }
        selectedOrderLabel.setText("Order " + selected.getNumber() + "  \u2014  " + selected.getCustomerName());
        String info = selected.getService() + "  \u2022  " + Ui.kg(selected.getWeightKg()) + "  \u2022  "
                + Ui.peso(selected.getTotal()) + "  \u2022  " + selected.getPaymentMethod();
        if (!selected.getPaymentReference().isEmpty()) {
            info += " (Ref. " + selected.getPaymentReference() + ")";
        }
        selectedInfoLabel.setText(info + "  \u2022  Due " + selected.getExpectedCompletion().format(Ui.DATE));
        statusCombo.setSelectedIndex(selected.getStatus());
        paymentStatusCombo.setSelectedItem(selected.getPaymentStatus());
        noteField.setText(selected.getStaffNote());
        viewDocumentButton.setText("View " + Ui.documentName(selected));
    }

    /** Opens this screen with the given order selected (used by the staff dashboard). */
    public void selectOrder(int orderId) {
        for (int i = 0; i < shown.size(); i++) {
            if (shown.get(i).getId() == orderId) {
                ordersTable.setRowSelectionInterval(i, i);
                ordersTable.scrollRectToVisible(ordersTable.getCellRect(i, 0, true));
            }
        }
    }

    private void saveUpdate() {
        if (selected == null) {
            return;
        }
        int status = statusCombo.getSelectedIndex();
        String payment = (String) paymentStatusCombo.getSelectedItem();
        if (status == Order.CLAIMED && !Order.PAID.equals(payment)) {
            Ui.warn(this, "Record the payment as Paid before marking the laundry as Claimed.");
            return;
        }
        Order order = selected;
        Session.updateOrder(order, status, payment, noteField.getText().trim());
        loadOrders();
        Ui.info(this, "Order " + order.getNumber() + " updated: " + order.getStatusName() + ", " + order.getPaymentStatus() + ".");
    }

