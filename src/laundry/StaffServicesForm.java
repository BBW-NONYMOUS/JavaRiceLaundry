    private void save() {
        double[] rates = new double[CODES.length];
        int[] days = new int[CODES.length];
        for (int i = 0; i < CODES.length; i++) {
            String name = Session.getService(CODES[i]).getName();
            rates[i] = Ui.parseNumber(rateFields()[i].getText());
            if (rates[i] <= 0 || rates[i] > 10000) {
                Ui.warn(this, "Please enter a valid rate per kg for " + name + ".");
                return;
            }
            double day = Ui.parseNumber(dayFields()[i].getText());
            if (day < 0 || day > 30 || day != Math.floor(day)) {
                Ui.warn(this, "Turnaround for " + name + " must be a whole number of days from 0 to 30.");
                return;
            }
            days[i] = (int) day;
        }
        for (int i = 0; i < CODES.length; i++) {
            Session.updateService(CODES[i], rates[i], days[i], availableBoxes()[i].isSelected());
        }
        Ui.info(this, "Service and pricing list saved.");
    }

